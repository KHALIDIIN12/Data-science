#arithmetic operators are basically used to perform mathematical operation on numbers
# + is the addition operator
# - is the subtraction operator
# * is the multiplication operator
# / is the division operator

print(80 + 10) #this will print 90 because it added 80 and 10
print(80 - 10) #this will print 70 because it subtracted 80 from 10
print(80 * 10) #this will print 800 because it multiplied 80 and 10
print(80 / 10) #this will print 8.0 because it divided 80 by 10