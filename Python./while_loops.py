# while loops are used to repeat a block of code as long as a condition is true
L = 1
while L < 20: # as long as L is less than 20, the loop will continue to run
    print(L)
    L = L + 1 # this will increment L by 1 each time the loop runs, 
               #so that eventually L will be equal to 20 and the loop will stop
               
