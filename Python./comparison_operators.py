#comparison operators are used to compare two values and return a boolean value (True or False)
# > is the greater than operator
# < is the less than operator
# == is the equal to operator
# <= is the less than or equal to operator
# >= is the greater than or equal to operator
# != is the not equal to operator

print(80 >10) # this will print True because 80 is greater than 10
print(80 <10) # this will print False because 80 is not less than 10
print(80 == 10) # this will print False because 80 is not equal to 10
print(80 <= 10) # this will print False because 80 is not less than or equal to 10
print(80 >= 10) # this will print True because 80 is greater than or equal to 10
print(80 != 10) # this will print True because 80 is not equal to 10
